#!/usr/bin/env bash
#
# Point the frontend at the branch's stack pair: writes frontend/public/config.js from the two
# stacks' outputs (API URL, Cognito domain and client id, meal hours) and the addresses of
# lib/params.sh. The browser loads the file as a plain script before the app bundle, so
# retargeting needs no rebuild.
#
#   ./scripts/lib/app-config.sh   write config.js for the branch's stack pair
#   -h, --help                    show this help
#
# deploy.sh runs it after every backend deploy and before every frontend publish.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=lib/app-env.sh
source "$SCRIPT_DIR/lib/app-env.sh"

case "${1:-}" in
    -h | --help) print_help; exit 0 ;;
    "") ;;
    *) usage_error "Unknown argument: $1" ;;
esac

for tool in aws jq git; do
    command -v "$tool" >/dev/null || die "Required tool not found: $tool"
done
load_aws_config
load_params
resolve_stack_pair

OUTPUTS="$(stack_outputs)"
HOSTED_UI_DOMAIN="$(cognito_output HostedUiDomain)"
CLIENT_ID="$(cognito_output UserPoolClientId)"
API_URL="$(stack_output "$OUTPUTS" ApiUrl)"
FIRST_MEAL_HOUR="$(stack_output "$OUTPUTS" FirstMealHour)"
MEAL_GAP_HOURS="$(stack_output "$OUTPUTS" MealGapHours)"
# The chat's answering service reaches the browser as availability alone; the URL and its key
# stay on the backend.
if [[ -n "$RAG_API_URL" ]]; then CHAT_AVAILABLE=true; else CHAT_AVAILABLE=false; fi

# The admin is shown to rejected sign-ins as the access contact; the developer's address gates
# the diagnostic readings the app shows of itself.
mkdir -p "$(dirname "$APP_CONFIG_FILE")"
cat >"$APP_CONFIG_FILE" <<CONFIG
// Generated by scripts/lib/app-config.sh — do not edit by hand.
window.CONFIG = {
  cognitoDomain: "$HOSTED_UI_DOMAIN",
  clientId: "$CLIENT_ID",
  apiUrl: "$API_URL",
  redirectUri: window.location.origin + "/",
  rootEmail: "${ADMIN_EMAIL}",
  devEmail: "${DEV_EMAIL}",
  firstMealHour: ${FIRST_MEAL_HOUR},
  mealGapHours: ${MEAL_GAP_HOURS},
  chatAvailable: ${CHAT_AVAILABLE},
};
CONFIG

ok "Wrote $APP_CONFIG_FILE for stack '$STACK_NAME'."
